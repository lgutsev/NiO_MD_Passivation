# Execution
# ---------------------------------------------------------------------------


def run_deck(
    commands,
    *,
    workdir: Path,
    engine_spec=None,
    n_atoms: int,
    want_per_atom: bool = False,
) -> dict:
    """Execute a rendered deck and read energy, forces, stress and site energies back.

    Always writes the deck to ``workdir`` first, whichever route runs it, so a
    failed job leaves behind exactly the input that failed.
    """
    workdir = Path(workdir)
    workdir.mkdir(parents=True, exist_ok=True)
    deck_path = workdir / DECK_FILE
    deck_path.write_text("\n".join(commands) + "\n", encoding="utf-8")

    if module_available("lammps"):
        return _run_with_module(commands, workdir, n_atoms, want_per_atom, deck_path)
    executable = (engine_spec.executable if engine_spec else None) or "lmp"
    if executable_available(executable):
        return _run_with_executable(executable, workdir, deck_path, want_per_atom)
    raise MissingDependencyError(
        "running a LAMMPS deck",
        ("lammps",),
        hint=(
            f"The rendered deck was written to {deck_path}. Install the LAMMPS python "
            "module, put an 'lmp' executable on PATH, or run that deck yourself."
        ),
    )


def _run_with_module(commands, workdir: Path, n_atoms: int, want_per_atom: bool, deck_path: Path):
    import numpy as np
    from lammps import LMP_STYLE_ATOM, LMP_TYPE_VECTOR, lammps

    started = time.perf_counter()
    # The deck names its data, dump and thermo files relatively, so the run has
    # to happen in the job directory. `shell cd` would break on any path with a
    # space in it, which on Windows is most of them.
    with _working_directory(workdir):
        lmp = lammps(cmdargs=["-log", LOG_FILE, "-screen", "none"])
        try:
            lmp.commands_list(list(commands))
            thermo = {key: float(lmp.get_thermo(key)) for key in THERMO_KEYS}
            ids = np.array(lmp.numpy.extract_atom("id")).flatten()
            order = np.argsort(ids)
            forces = np.array(lmp.numpy.extract_atom("f"))[order]
            per_atom = None
            if want_per_atom:
                values = lmp.numpy.extract_compute(
                    "mlip_pe_atom", LMP_STYLE_ATOM, LMP_TYPE_VECTOR
                )
                per_atom = np.array(values).flatten()[order]
            positions = np.array(lmp.numpy.extract_atom("x"))[order]
        finally:
            lmp.close()
    return {
        "route": "python-module",
        "thermo": thermo,
        "forces": [[float(c) for c in row] for row in forces],
        "per_atom_energy": [float(v) for v in per_atom] if per_atom is not None else None,
        "positions": [[float(c) for c in row] for row in positions],
        "wall_time_s": time.perf_counter() - started,
        "deck_path": str(deck_path),
        "log_path": str(workdir / LOG_FILE),
    }


def _run_with_executable(executable: str, workdir: Path, deck_path: Path, want_per_atom: bool):
    started = time.perf_counter()
    completed = subprocess.run(
        [executable, "-in", deck_path.name, "-log", LOG_FILE],
        cwd=str(workdir),
        capture_output=True,
        text=True,
        check=False,
    )
    if completed.returncode != 0:
        tail = (completed.stderr or completed.stdout or "").strip().splitlines()[-20:]
        raise MlipError(
            f"{executable} exited with status {completed.returncode} for {deck_path}.\n"
            + "\n".join(tail)
        )
    thermo = _read_thermo(workdir / THERMO_FILE)
    forces, per_atom, positions = _read_dump(workdir / DUMP_FILE)
    return {
        "route": "executable",
        "thermo": thermo,
        "forces": forces,
        "per_atom_energy": per_atom if want_per_atom else None,
        "positions": positions,
        "wall_time_s": time.perf_counter() - started,
        "deck_path": str(deck_path),
        "log_path": str(workdir / LOG_FILE),
    }


@contextlib.contextmanager
def _working_directory(path: Path):
    previous = os.getcwd()
    os.chdir(path)
    try:
        yield
    finally:
        os.chdir(previous)


def _read_thermo(path: Path) -> dict[str, float]:
    if not path.exists():
        raise MlipError(f"LAMMPS did not write {path}; the run did not reach its thermo block")
    values: dict[str, float] = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        parts = line.split()
        if len(parts) == 2:
            try:
                values[parts[0]] = float(parts[1])
            except ValueError:
                continue
    return values


def _read_dump(path: Path):
    """Read the single-snapshot custom dump written by the rendered deck."""
    if not path.exists():
        raise MlipError(f"LAMMPS did not write {path}; forces could not be read back")
    lines = path.read_text(encoding="utf-8").splitlines()
    try:
        header = next(i for i, line in enumerate(lines) if line.startswith("ITEM: ATOMS"))
    except StopIteration:
        raise MlipError(f"{path} contains no ATOMS section") from None
    columns = lines[header].split()[2:]
    index = {name: position for position, name in enumerate(columns)}
    rows = [line.split() for line in lines[header + 1:] if line.strip()]
    rows.sort(key=lambda row: int(row[index["id"]]))
    forces = [[float(row[index[c]]) for c in ("fx", "fy", "fz")] for row in rows]
    positions = [[float(row[index[c]]) for c in ("x", "y", "z")] for row in rows]
    per_atom = (
        [float(row[index["c_mlip_pe_atom"]]) for row in rows]
        if "c_mlip_pe_atom" in index
        else None
    )
    return forces, per_atom, positions


def stress_from_pressure(thermo: dict, units: str) -> list[float] | None:
    """Convert LAMMPS pressure components to a canonical Voigt stress.

    Two conversions, both explicit: LAMMPS reports pressure (``metal``: bars;
    ``real``: atmospheres, which this subsystem does not accept), and pressure
    is the negative of stress under the convention ASE and this subsystem use.
    """
    keys = ("pxx", "pyy", "pzz", "pyz", "pxz", "pxy")
    if not all(key in thermo for key in keys):
        return None
    if units != "metal":
        # Only metal units have a bar-based pressure this subsystem converts.
        return None
    return [-thermo[key] / EV_PER_ANGSTROM3_IN_BAR for key in keys]


def energy_to_eV(value: float, units: str) -> float:
    return value * lammps_unit_system(units).energy_in_eV


def forces_to_eV_per_A(forces, units: str):
    factor = lammps_unit_system(units).force_in_eV_per_angstrom
    return [[component * factor for component in row] for row in forces]


