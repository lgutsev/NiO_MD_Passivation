"""The LAMMPS engine: deck rendering first, execution second.

Rendering is separated from running on purpose. The exact ``pair_style`` and
``pair_coeff`` strings -- and the whole input deck around them -- are what a
LAMMPS run actually *is*, so :func:`render_deck` is pure, testable, and
callable on a machine with no LAMMPS at all. ``mlip validate`` renders the
deck it would submit; ``mlip_manifest.json`` stores it verbatim.

Execution then has two routes, in order of preference:

* the LAMMPS Python module, which can hand back forces and per-atom energies
  directly from memory;
* an ``lmp`` executable, driven through a written deck plus a dump file.

Units: LAMMPS ``metal`` already speaks eV and Angstrom, but ``real`` does not,
and LAMMPS reports *pressure* in bars where this subsystem's canonical stress
is eV/Angstrom^3 with the opposite sign. Both conversions happen in
:func:`stress_from_pressure`, never implicitly.
"""
from __future__ import annotations

import contextlib
import os
import subprocess
import time
from pathlib import Path

from ..capabilities import CapabilitySet
from ..environment import Availability, executable_available, module_available
from ..errors import MissingDependencyError, MlipError
from ..specs import LammpsMlipPotentialSpec, SimulationSpec
from ..units import EV_PER_ANGSTROM3_IN_BAR, LAMMPS_METAL, lammps_unit_system
from .base import EngineRuntime

DATA_FILE = "structure.lmp"
DECK_FILE = "in.lammps"
DUMP_FILE = "forces.dump"
THERMO_FILE = "thermo_result.txt"
TRAJECTORY_FILE = "smoke_md.lammpstrj"
LOG_FILE = "log.lammps"

#: LAMMPS timestep units per unit style. ``metal`` counts picoseconds, ``real``
#: femtoseconds; getting this wrong is a factor of 1000 in the dynamics.
TIMESTEP_PER_FS = {"metal": 1e-3, "real": 1.0}
#: Thermostat/barostat damping is quoted in the same time unit as the timestep.
DAMPING_PER_FS = TIMESTEP_PER_FS

THERMO_KEYS = ("pe", "ke", "etotal", "temp", "press", "pxx", "pyy", "pzz", "pyz", "pxz", "pxy")


class LammpsEngine(EngineRuntime):
    kind = "lammps"
    requires = ()
    native_units = LAMMPS_METAL.name

    def capabilities(self) -> CapabilitySet:
        """LAMMPS carries everything; whether a pair style supplies it is separate."""
        return CapabilitySet(
            energy=True,
            forces=True,
            stress=True,
            per_atom_energy=True,
            periodic=True,
            # Not yet honoured by the rendered deck (one boundary style for all
            # axes; no frozen-atom groups), so such jobs are refused at validate.
            partial_periodic=False,
            fixed_atoms=False,
            gpu=True,
            elements=None,
            precisions=None,
            engines=frozenset({"lammps"}),
            native_units=self.native_units,
            notes=(
                "LAMMPS reports pressure in bars; this subsystem converts to "
                "eV/Angstrom^3 stress with the sign flipped",
            ),
        )

    def availability(self) -> Availability:
        if module_available("lammps"):
            return Availability(True, (), "LAMMPS python module")
        executable = self.spec.executable or "lmp"
        if executable_available(executable):
            return Availability(True, (), f"{executable} executable")
        return Availability(
            False,
            ("lammps",),
            "neither the LAMMPS python module nor an 'lmp' executable was found",
        )


# ---------------------------------------------------------------------------
# Deck rendering (pure; no LAMMPS required)
# ---------------------------------------------------------------------------


def render_deck(
    potential: LammpsMlipPotentialSpec,
    simulation: SimulationSpec,
    *,
    n_types: int,
    periodic: bool = True,
    data_file: str = DATA_FILE,
    dump_file: str = DUMP_FILE,
    thermo_file: str = THERMO_FILE,
    trajectory_file: str = TRAJECTORY_FILE,
    thermo_interval: int | None = None,
) -> tuple[str, ...]:
    """Render the complete input deck as an ordered tuple of commands.

    Pure: no files are written and no LAMMPS is needed. The pair commands come
    from :meth:`LammpsMlipPotentialSpec.render_pair_commands`, so what is
    validated, what is stored in the manifest and what is executed are the
    same strings.
    """
    if n_types != len(potential.type_map):
        raise ValueError(
            f"deck asks for {n_types} atom types but the potential maps "
            f"{len(potential.type_map)}"
        )
    boundary = "p p p" if periodic else "f f f"
    lines = [
        f"# generated by nio-md-prep mlip ({potential.label})",
        "clear",
        f"units {potential.units}",
        f"atom_style {potential.atom_style}",
        f"boundary {boundary}",
        "atom_modify map yes",
        "box tilt large",
    ]
    if potential.newton:
        lines.insert(2, f"newton {potential.newton}")
    lines.append(f"read_data {data_file}")
    lines.extend(potential.render_pair_commands())
    lines.append("")
    lines.append("compute mlip_pe_atom all pe/atom")
    lines.append("thermo_style custom step " + " ".join(THERMO_KEYS))

    if simulation.task == "md":
        lines.extend(
            _md_block(
                potential,
                simulation,
                trajectory_file=trajectory_file,
                dump_file=dump_file,
                thermo_interval=thermo_interval,
            )
        )
    else:
        lines.extend(
            [
                "thermo 1",
                f"dump mlip_forces all custom 1 {dump_file} id type x y z fx fy fz c_mlip_pe_atom",
                "dump_modify mlip_forces sort id",
                "run 0",
            ]
        )
    lines.extend(_thermo_dump_block(thermo_file))
    return tuple(lines)


def _md_block(
    potential: LammpsMlipPotentialSpec,
    simulation: SimulationSpec,
    *,
    trajectory_file: str,
    dump_file: str,
    thermo_interval: int | None,
) -> list[str]:
    timestep = simulation.timestep_fs * TIMESTEP_PER_FS[potential.units]
    # Defaults resolve through the one shared constant (specs.DEFAULT_*_DAMPING_FS).
    damping = simulation.resolved_thermostat_damping_fs * DAMPING_PER_FS[potential.units]
    barostat_damping = simulation.resolved_barostat_damping_fs * DAMPING_PER_FS[potential.units]
    interval = thermo_interval or max(1, simulation.log_interval)
    lines = [f"timestep {timestep:.10g}"]
    if simulation.temperature_K:
        seed = simulation.seed if simulation.seed is not None else 12345
        lines.append(
            f"velocity all create {simulation.temperature_K:.6g} {seed} "
            "mom yes rot yes dist gaussian"
        )
    temperature = simulation.temperature_K
    if simulation.ensemble == "nve":
        lines.append("fix mlip_integrate all nve")
    elif simulation.ensemble == "nvt":
        lines.append(
            f"fix mlip_integrate all nvt temp {temperature:.6g} {temperature:.6g} "
            f"{damping:.10g}"
        )
    elif simulation.ensemble == "npt":
        pressure = simulation.pressure_bar
        lines.append(
            f"fix mlip_integrate all npt temp {temperature:.6g} {temperature:.6g} "
            f"{damping:.10g} iso {pressure:.6g} {pressure:.6g} {barostat_damping:.10g}"
        )
    lines.extend(
        [
            f"thermo {interval}",
            f"dump mlip_traj all custom {max(1, simulation.trajectory_interval)} "
            f"{trajectory_file} id type x y z",
            "dump_modify mlip_traj sort id",
            f"run {simulation.steps}",
            f"write_dump all custom {dump_file} id type x y z fx fy fz c_mlip_pe_atom "
            "modify sort id",
        ]
    )
    return lines


def _thermo_dump_block(thermo_file: str) -> list[str]:
    """Print the thermo quantities this subsystem reads back, one per line.

    Used by the executable route, which has no way to reach into LAMMPS's
    memory. Harmless under the Python route.
    """
    lines = []
    for index, key in enumerate(THERMO_KEYS):
        lines.append(f"variable mlip_{key} equal {key}")
        redirect = "file" if index == 0 else "append"
        lines.append(f'print "{key} ${{mlip_{key}}}" {redirect} {thermo_file}')
    return lines


def write_data_file(atoms, potential: LammpsMlipPotentialSpec, path: Path) -> Path:
    """Write the structure as a LAMMPS data file in the potential's type order.

    ``specorder`` is taken from ``potential.type_map``, which is what makes the
    ``pair_coeff`` element list and the data file agree. Without it, LAMMPS
    would assign types by order of appearance and silently mislabel elements.
    """
    from ase.io import write as ase_write

    from ..structures import to_lammps_type_order

    to_lammps_type_order(atoms, potential.type_map)  # validates coverage first
    specorder = [potential.type_map[t] for t in sorted(potential.type_map)]
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    ase_write(
        str(path),
        atoms,
        format="lammps-data",
        specorder=specorder,
        atom_style=potential.atom_style,
        masses=True,
    )
    return path


